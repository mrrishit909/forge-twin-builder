export function SimulationPanel() {
  const view = useApp((s) => s.view), active = useApp((s) => s.active), r = useApp((s) => s.sims[s.active]), opt = useApp((s) => s.optimize);
  const [playing, setPlaying] = useState(playback.playing);
  if (view !== "simulate" || !r) return opt ? <OptimizePanel /> : null;
  const k = r.kpis, sc = activeScene();
  const work = Object.entries(k.utilization).filter(([id]) => ["machine", "robot"].includes(sc?.assets.find((a) => a.id === id)?.type ?? ""));
  return (
    <aside className="panel right" aria-label="Simulation results">
      <h2>Simulation · {active} <small>{k.runs} shifts of 8 h, {n(Math.round(r.ms))} ms</small></h2>
      <dl className="kv">
        <dt>Throughput</dt><dd>{fmtE(k.throughputPerH)} parts/h</dd>
        <dt>Cycle time</dt><dd>{fmtE({ ...k.cycleMeanS, mean: k.cycleMeanS.mean / 60, lo: k.cycleMeanS.lo / 60, hi: k.cycleMeanS.hi / 60 })} min</dd>
        <dt>Work in process</dt><dd>{fmtE(k.wipAvg)} parts</dd>
        <dt>Constraint</dt><dd>{k.supplyLimitedShare >= 0.5 ? <>raw-material supply ({k.releaseRatePerH.toFixed(0)}/h); busiest station {name(k.bottleneck[0].id)}</> : <>{name(k.bottleneck[0].id)} (bottleneck in {Math.round(k.bottleneck[0].share * 100)}% of shifts)</>}</dd>
      </dl>
      <h3>Utilization (busy share, 95% interval)</h3>
      <table className="util"><tbody>{work.map(([id, e]) => (
        <tr key={id}><th scope="row">{name(id)}</th><td><span className="bar" style={{ width: `${Math.round(e.mean * 100)}%` }} />{Math.round(e.mean * 100)}%</td></tr>
      ))}</tbody></table>
      <div className="row"><button onClick={() => { playback.playing = !playback.playing; setPlaying(playback.playing); }}>{playing ? "Pause playback" : "Play the first hour (60×)"}</button><button onClick={() => send({ type: "BACK" })}>Back to editor</button></div>
      <details><summary>Assumptions</summary><ul className="small">{k.assumptions.map((a) => <li key={a}>{a}</li>)}</ul></details>
      {opt ? <OptimizePanel /> : null}
    </aside>
  );
}

