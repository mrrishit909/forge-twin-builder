function Spark({ topic, label, unit, warn }: { topic: string; label: string; unit: string; warn?: number }) {
  const [, tick] = useState(0);
  useEffect(() => { const iv = setInterval(() => tick((k) => k + 1), 500); return () => clearInterval(iv); }, []);
  const h = historyOf(topic), v = valueOf(topic);
  const stale = live.lastAt && Date.now() - live.lastAt > 4000;
  const max = Math.max(1, ...h, warn ?? 0), min = Math.min(0, ...h);
  const pts = h.map((x, i) => `${(i / Math.max(1, h.length - 1)) * 100},${30 - ((x - min) / (max - min)) * 28}`).join(" ");
  return (
    <figure className="spark">
      <figcaption>{label} <b className={stale ? "stale" : ""}>{v === undefined ? "–" : `${v.toFixed(unit === "rpm" ? 0 : 1)} ${unit}`}</b>{stale ? <small> stale</small> : null}</figcaption>
      <svg viewBox="0 0 100 32" preserveAspectRatio="none" aria-hidden><polyline points={pts} fill="none" stroke="currentColor" strokeWidth="1" vectorEffect="non-scaling-stroke" />{warn ? <line x1="0" x2="100" y1={30 - ((warn - min) / (max - min)) * 28} y2={30 - ((warn - min) / (max - min)) * 28} className="warn-line" /> : null}</svg>
    </figure>
  );
}

function BindingEditor({ assetId }: { assetId: string }) {
  const conn = useApp((s) => s.connector);
  const bindings = useApp((s) => s.scenes[s.active]?.bindings ?? []);
  const [exprs, setExprs] = useState<Record<string, string>>(Object.fromEntries(BINDABLE.map((b) => [b.property, b.transform])));
  const [err, setErr] = useState<string | null>(null);
  const has = (p: string) => bindings.some((b) => b.assetId === assetId && b.targetProperty === p);
  if (conn.state === "idle" || !conn.info) return <button className="primary" onClick={() => connectTelemetry()}>Connect MQTT telemetry</button>;
  return (
    <div className="bindings">
      <p className="muted small">{conn.info.label} · topics <code>{topicOf("demo", assetId, "rpm").replace("/rpm", "/#")}</code></p>
      {BINDABLE.map((b) => {
        let valid = true; try { compile(exprs[b.property]); } catch { valid = false; }
        return (
          <div key={b.property} className="bind-row">
            <label>{b.label} <input value={exprs[b.property]} aria-invalid={!valid} onChange={(e) => setExprs({ ...exprs, [b.property]: e.target.value })} /></label>
            <button disabled={!valid} aria-pressed={has(b.property)} onClick={() => setErr(bind(assetId, b.metric, b.property, exprs[b.property]))}>{has(b.property) ? "Bound" : "Bind"}</button>
          </div>
        );
      })}
      {err ? <p role="alert" className="errors">{err}</p> : null}
    </div>
  );
}

export function Inspector() {
  const sel = useApp((s) => (s.selected ? s.scenes[s.active]?.assets.find((a) => a.id === s.selected) ?? null : null));
  const view = useApp((s) => s.view);
  const ref = useRef<HTMLElement>(null);
  // shared-element transition: the panel grows out of the asset's place on screen
  useEffect(() => {
    const el = ref.current;
    if (!el || !sel || get().reduced) return;
    import("../scene/overlay.ts").then(({ sceneApi }) => {
      const p = sceneApi.project(sel.transform.position);
      if (!p) return;
      const r = el.getBoundingClientRect();
      el.animate([{ transform: `translate(${p[0] - r.left - r.width / 2}px, ${p[1] - r.top - r.height / 2}px) scale(0.15)`, opacity: 0.2 }, { transform: "none", opacity: 1 }], { duration: 420, easing: "cubic-bezier(.2,.8,.2,1)" });
    });
  }, [sel?.id]); // eslint-disable-line react-hooks/exhaustive-deps
  if (!sel || view !== "inspect") return null;
  const spec = LIBRARY[sel.type];
  const t = (m: "rpm" | "temperature" | "vibration") => topicOf("demo", sel.id, m);
  return (
    <aside ref={ref} className="panel right inspector" aria-label={`Inspector: ${sel.name}`}>
      <h2>{sel.name} <small>{spec.label}</small></h2>
      <dl className="kv">
        <dt>Position</dt><dd>{sel.transform.position.map((x) => x.toFixed(1)).join(", ")} m</dd>
        <dt>Rotation</dt><dd>{sel.transform.rotation[1]}°</dd>
        <dt>Capex</dt><dd>{spec.costUsd ? `$${n(spec.costUsd)}` : "–"}</dd>
      </dl>
      <h3>Properties</h3>
      <div className="props">
        {Object.entries(sel.props).map(([k, v]) => <label key={k}>{k} <input type="number" step="any" value={v} onChange={(e) => setProp(sel.id, k, Number(e.target.value))} /></label>)}
      </div>
      <Flow id={sel.id} />
      {sel.type === "machine" ? (
        <>
          <h3>Live telemetry</h3>
          <Spark topic={t("rpm")} label="RPM" unit="rpm" />
          <Spark topic={t("temperature")} label="Temperature" unit="°C" warn={sel.props.maxTempC} />
          <Spark topic={t("vibration")} label="Vibration RMS" unit="mm/s" />
          <h3>Bindings</h3>
          <BindingEditor assetId={sel.id} />
        </>
      ) : null}
      {sel.type === "buffer" ? <button onClick={() => optimizeBuffer(sel.id)}>Size this buffer</button> : null}
      <div className="row"><button onClick={() => select(null)}>Back to overview</button><button onClick={() => removeAsset(sel.id)}>Remove</button></div>
    </aside>
  );
}

function Flow({ id }: { id: string }) {
  const sc = useApp((s) => s.scenes[s.active]);
  if (!sc) return null;
  const ins = sc.links.filter((l) => l.to === id).map((l) => l.from), outs = sc.links.filter((l) => l.from === id).map((l) => l.to);
  const others = sc.assets.filter((a) => a.id !== id);
  return (
    <div className="flow">
      <h3>Flow</h3>
      <p className="small">Fed by: {ins.length ? ins.map(name).join(", ") : "nothing"} · Feeds: {outs.length ? outs.map(name).join(", ") : "nothing"}</p>
      <div className="row">
        <label className="inline">Fed by <select aria-label="Add an upstream asset" value="" onChange={(e) => e.target.value && linkAssets(e.target.value, id)}><option value="">add…</option>{others.filter((a) => !ins.includes(a.id) && a.type !== "sink").map((a) => <option key={a.id} value={a.id}>{a.name}</option>)}</select></label>
        <label className="inline">Feeds <select aria-label="Add a downstream asset" value="" onChange={(e) => e.target.value && linkAssets(id, e.target.value)}><option value="">add…</option>{others.filter((a) => !outs.includes(a.id) && a.type !== "source").map((a) => <option key={a.id} value={a.id}>{a.name}</option>)}</select></label>
      </div>
    </div>
  );
}

