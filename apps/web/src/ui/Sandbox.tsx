export function ComparePanel() {
  const view = useApp((s) => s.view), c = useApp((s) => s.comparison), active = useApp((s) => s.active);
  const sc = useApp((s) => s.scenes);
  if (view !== "compare" || !c) return null;
  const added = (sc[active]?.assets ?? []).filter((a) => !sc.production?.assets.some((b) => b.id === a.id));
  const capex = added.reduce((t, a) => t + LIBRARY[a.type].costUsd, 0);
  type K = NonNullable<typeof c>["base"];
  const row = (label: string, f: (k: K) => string) => <tr><th scope="row">{label}</th><td>{f(c.base)}</td><td>{f(c.branch)}</td></tr>;
  return (
    <aside className="panel right" aria-label="Branch comparison">
      <h2>{active} vs production <small>30 paired shifts, common random numbers</small></h2>
      <table className="cmp">
        <thead><tr><th scope="col" /><th scope="col">production</th><th scope="col">{active}</th></tr></thead>
        <tbody>
          {row("Throughput/h", (k) => fmtE(k.throughputPerH))}
          {row("Cycle time, min", (k) => fmtE({ ...k.cycleMeanS, mean: k.cycleMeanS.mean / 60, lo: k.cycleMeanS.lo / 60, hi: k.cycleMeanS.hi / 60 }))}
          {row("WIP, parts", (k) => fmtE(k.wipAvg))}
          {row("Constraint", (k) => (k.supplyLimitedShare >= 0.5 ? `supply ${k.releaseRatePerH.toFixed(0)}/h` : name(k.bottleneck[0].id)))}
        </tbody>
      </table>
      <p className="delta"><b>{c.throughputDiff.mean >= 0 ? "+" : ""}{c.throughputDiff.mean.toFixed(1)} parts/h</b> (95% interval {c.throughputDiff.lo.toFixed(1)} to {c.throughputDiff.hi.toFixed(1)}){c.significant ? "" : ", not distinguishable from zero"}. Added capex ${n(capex)}{added.length ? ` (${added.map((a) => a.name).join(", ")})` : ""}.</p>
      <details open><summary>Assumptions and confidence</summary><ul className="small">{c.base.assumptions.map((a) => <li key={a}>{a}</li>)}<li>The interval is on paired differences: both branches see the same arrivals, times and failures.</li></ul></details>
      <div className="row"><button onClick={() => send({ type: "BACK" })}>Back to editor</button></div>
    </aside>
  );
}

