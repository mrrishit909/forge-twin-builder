// Synthetic data generator: the demo factory scene, plus the evaluation numbers quoted in the README (simulation KPIs for the
// production line and the expansion branch, buffer sizing, predictive-maintenance detection over 50 seeds), with provenance.
// Run: node data/simulators/generate.ts   (deterministic)
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { templateFactory, serialize, compare, sizeBuffer, newAsset, MachineSim, vibrationAlarm, DEMO_MACHINES, LIBRARY, type Scene } from "../../packages/domain/src/index.ts";

const out = new URL("../fixtures/", import.meta.url);
mkdirSync(out, { recursive: true });
const t0 = Date.now();
const prod = templateFactory();
/** The expansion the demo builds by hand: a second CNC beside M1, fed by the infeed conveyor, feeding buffer B1. */
export function expansionOf(s: Scene): Scene {
  const ex = structuredClone(s);
  ex.assets.push({ ...newAsset("machine", "m1b", [-7, 0, 3], "CNC mill M1b"), props: { ...s.assets.find((a) => a.id === "m1")!.props } });
  ex.links.push({ from: "c1", to: "m1b" }, { from: "m1b", to: "b1" });
  return ex;
}
const cmp = compare(prod, expansionOf(prod), 30);
const buffer = sizeBuffer(prod, "b1", 8, 10);

const pdm = { faulty: [] as number[], missed: 0, early: 0, healthyRuns: 50, healthyAlarms: 0 };
for (let s = 1; s <= 50; s++) {
  const m = new MachineSim({ ...DEMO_MACHINES[1], faultAtS: 1500, failAfterS: 2400 }, s);
  const xs = Array.from({ length: 3900 }, (_, i) => { const v = m.step(); return { t: i + 1, vibration: v.vibration, running: v.status === 0 }; });
  const a = vibrationAlarm(xs).alarmAt;
  if (a === null) pdm.missed++; else if (a < 1500) pdm.early++; else pdm.faulty.push((3900 - a) / 60);
}
for (let s = 1; s <= pdm.healthyRuns; s++) {
  const m = new MachineSim({ ...DEMO_MACHINES[1], faultAtS: null }, 1000 + s);
  const xs = Array.from({ length: 8 * 3600 }, (_, i) => { const v = m.step(); return { t: i + 1, vibration: v.vibration, running: v.status === 0 }; });
  if (vibrationAlarm(xs).alarmAt !== null) pdm.healthyAlarms++;
}
pdm.faulty.sort((a, b) => a - b);
const q = (p: number) => +pdm.faulty[Math.floor(p * (pdm.faulty.length - 1))].toFixed(1);

const sceneText = serialize(prod);
writeFileSync(new URL("template-scene.json", out), sceneText);
const evaluation = {
  simulation: { production: cmp.base, expansion: cmp.branch, throughputGainPerH: cmp.throughputDiff, significant: cmp.significant },
  bufferSizing: buffer,
  predictiveMaintenance: { runs: 50, detected: pdm.faulty.length, missed: pdm.missed, alarmsBeforeFault: pdm.early, leadMinutes: { p10: q(0.1), median: q(0.5), p90: q(0.9) }, healthy8hRuns: pdm.healthyRuns, healthyRunsWithAlarm: pdm.healthyAlarms, note: "the detector and the fault come from the same generator; this checks the code, not real-world accuracy" },
  library: Object.fromEntries(Object.entries(LIBRARY).map(([k, v]) => [k, { props: v.props, costUsd: v.costUsd }])),
};
writeFileSync(new URL("evaluation.json", out), JSON.stringify(evaluation, null, 1));
writeFileSync(new URL("provenance.json", out), JSON.stringify({
  datasets: [
    { name: "demo factory scene", provider: "synthetic: packages/domain/src/scene.ts templateFactory()", license: "MIT (generated by this repository)", version: "scene-v1", sha256: createHash("sha256").update(sceneText).digest("hex") },
    { name: "telemetry", provider: "synthetic: packages/domain/src/telemetry.ts MachineSim (seeded, 1 Hz)", license: "MIT", version: "telemetry-v1" },
  ],
  qualityChecks: { sceneParses: true, linksPortToPort: true, simulationReplicas: 30 },
  generatedInMs: Date.now() - t0,
}, null, 1));
console.log(JSON.stringify({ production: cmp.base.throughputPerH, expansion: cmp.branch.throughputPerH, gain: cmp.throughputDiff, bottleneck: [cmp.base.bottleneck[0], cmp.branch.bottleneck[0]], buffer: buffer.rows.map((r) => [r.capacity, +r.throughputPerH.toFixed(1)]), chosen: buffer.chosen, pdm: evaluation.predictiveMaintenance, ms: Date.now() - t0 }, null, 0));
